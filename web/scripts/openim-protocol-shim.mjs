// @openim/client-sdk imports "@openim/protocol/lib/pb/sdkws/sdkws" at runtime,
// but every published @openim/protocol tarball ships only the .d.ts for that
// path and no .js, so the import fails to resolve in any consumer (upstream
// packaging bug - the symbols are exported from the package root bundle).
//
// This script repairs the install by writing a one-line re-export next to the
// missing file. It is idempotent, does nothing when either package is absent,
// and runs on every install so a clean checkout works without a patch tool.
import { existsSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const webRoot = dirname(dirname(fileURLToPath(import.meta.url)));
const shimDir = join(webRoot, 'node_modules', '@openim', 'protocol', 'lib', 'pb', 'sdkws');
const rootBundle = join(webRoot, 'node_modules', '@openim', 'protocol', 'lib', 'index.js');
const shimPath = join(shimDir, 'sdkws.js');

if (!existsSync(rootBundle)) {
  process.exit(0);
}
// Written unconditionally so a corrected shim replaces an older one.
// The SDK binds this import to a namespace and reaches for PullOrder (and
// other sdkws symbols) directly on it, so the shim has to expose the sdkws
// namespace flattened on top of the root bundle, not the root bundle itself.
try {
  writeFileSync(
    shimPath,
    '// Generated by scripts/openim-protocol-shim.mjs - see that file for why.\n' +
      'const protocol = require("../../index.js");\n' +
      'module.exports = Object.assign({}, protocol, protocol.SdkWsProto);\n'
  );
  console.log('openim: wrote %s', shimPath);
} catch (err) {
  console.warn('openim: could not write the protocol shim: %s', err.message);
}
