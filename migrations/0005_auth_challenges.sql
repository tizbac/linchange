-- Pre-authentication challenges for second factors.
--
-- A user with TOTP enrolled gets an opaque challenge instead of tokens once
-- their password is correct. The challenge is not a session: it carries no
-- access, is short lived, and is consumed by the step that presents the second
-- factor. Keeping it in the database rather than in memory means a restart does
-- not silently strand a user mid-login, and two app instances behind a load
-- balancer both accept the same challenge.
--
-- A wrong code does not consume the challenge. The account lockout is the
-- attempt limiter, so burning the challenge on the first mistake would make a
-- mistyped code cost the user their whole password entry as well.
CREATE TABLE auth_challenges (
    -- id is an opaque random token generated by the application, never a
    -- predictable value: it is a bearer secret for the remainder of the
    -- password step.
    id            text        PRIMARY KEY,
    address       citext      NOT NULL REFERENCES users (address) ON DELETE CASCADE,
    -- impersonating remembers why the login was started, so the second-factor
    -- step cannot quietly drop it and issue a session for the admin's own
    -- account instead of the user being impersonated.
    impersonating citext,
    ip            inet,
    user_agent    text        NOT NULL DEFAULT '',
    created_at    timestamptz NOT NULL DEFAULT now(),
    -- expires_at is set by the application, not by a default, because the
    -- lifetime is configuration.
    expires_at    timestamptz NOT NULL,
    -- consumed_at is set by the step that succeeds. Expiry alone would let two
    -- concurrent requests with the same valid code both mint sessions.
    consumed_at   timestamptz
);

COMMENT ON TABLE auth_challenges IS
    'Short-lived pre-authentication state for a login awaiting a second factor. Not a session: grants nothing on its own.';

CREATE INDEX auth_challenges_expires_idx ON auth_challenges (expires_at);
CREATE INDEX auth_challenges_address_idx ON auth_challenges (address);
