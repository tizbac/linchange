#!/usr/bin/env python3
"""Generate e2e/eas/aswbxml_tags.py from the official [MS-ASWBXML] document.

Input is the plain-text extraction of the spec .docx. Output is a Python module
mapping namespace -> {element: token}, which the e2e ActiveSync client uses to
speak the protocol the way a real client does -- from the specification, never
from the server's own tables.
"""
import re
import sys

src, dst = sys.argv[1], sys.argv[2]
lines = open(src, encoding='utf8').read().split('\n')

headings = {}
for i, line in enumerate(lines):
    m = re.fullmatch(r'Code Page (\d+): (\S+)', line.strip())
    if m:
        headings[int(m.group(1))] = (i, m.group(2))

token_re = re.compile(r'^0x([0-9A-Fa-f]{2})\s*$')
version_re = re.compile(r'^(All|\d[\d.,\s]*)$')
header_words = {'Tag name', 'Token', 'Protocol versions'}

pages = []
for cp, (start, name) in sorted(headings.items()):
    end = min([i for cp2, (i, _) in headings.items() if i > start] or [len(lines)])
    for i in range(start + 1, end):
        if lines[i].startswith('Note ') or lines[i].startswith('WBXML code page'):
            end = i
            break

    # Skip the "Tag name / Token / Protocol versions" column header.
    body_start = start + 1
    while body_start < end and lines[body_start].strip() not in ('Tag name',):
        body_start += 1
    body_start += 3

    tags = {}
    for i in range(body_start, end):
        m = token_re.match(lines[i].strip())
        if not m:
            continue
        token = int(m.group(1), 16)
        j, parts = i - 1, []
        while j > start and lines[j].strip() and lines[j].strip() not in header_words \
                and not token_re.match(lines[j].strip()) and not version_re.match(lines[j].strip()):
            parts.insert(0, lines[j].strip())
            j -= 1
        if not parts:
            continue
        el = ' '.join(parts)
        el = re.sub(r'\s+[-\u2014]\s+see note.*$', '', el).strip()
        tags.setdefault(el, token)
    pages.append((cp, name, tags))

out = ['"""Exchange ActiveSync WBXML tag tables, generated from [MS-ASWBXML].',
       '',
       'Generated by tools/gen_aswbxml_tags.py from the official Microsoft',
       '[MS-ASWBXML] specification. The end-to-end ActiveSync test encodes its',
       'requests with these tables, so agreement between them and what the',
       'server understands means the server speaks the published protocol, not',
       'a dialect of its own.',
       '"""', '',
       '# namespace -> element name -> WBXML token', 'TAGS = {']
for cp, name, tags in pages:
    if not tags:
        continue
    out.append('    %r: {' % name)
    for el, tok in sorted(tags.items(), key=lambda kv: kv[1]):
        out.append('        %r: 0x%02X,  # code page %d' % (el, tok, cp))
    out.append('    },')
out += ['}', '',
        '# Code page number -> namespace, for SWITCH_PAGE on the wire.', 'CODE_PAGES = {']
for cp, name, tags in pages:
    if tags:
        out.append('    %d: %r,' % (cp, name))
out += ['}', '']
open(dst, 'w', encoding='utf8').write('\n'.join(out))
for cp, name, tags in pages:
    print('%2d %-18s %3d tags' % (cp, name, len(tags)), file=sys.stderr)
