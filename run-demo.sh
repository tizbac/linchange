echo -e "  Autodiscover: ${BLUE}${DEMO_BASE_URL}/autodiscover/autodiscover.xml${NC}"
echo -e "  EWS:          ${BLUE}${DEMO_BASE_URL}/ews/exchange.asmx${NC}"
echo -e "  EAS:          ${BLUE}${DEMO_BASE_URL}/eas/${NC}"
