compose() {
    $COMPOSE_CMD --env-file "$ENV_FILE" -f docker-compose.yml "$@"
}

# Build the image before starting. `compose up` reuses an existing image when
# there is one, which would leave the demo running whatever the binary was when
# the image was last built rather than what is in the working tree.

# Start a service, recovering once from a container that docker will not start.
#
# The compose services pin their container_name, so a container survives a
# `docker compose down` run from a different project name, or an interrupted
# run. It then still references the network it was created on, and if that
# network is gone docker refuses to start it, failing with "failed to set up
# container networking: network <id> not found". The container has to be
# recreated for the error to go away, which is what the retry does.
compose_up() {
    local service="$1" container="$2"
    if compose up -d "$service"; then
        return 0
    fi
    echo -e "${YELLOW}Recreating ${container}: it was left behind holding a network that no longer exists.${NC}"
    compose rm -sf "$service" >/dev/null 2>&1 || true
    docker rm -f "$container" >/dev/null 2>&1 || true
    compose up -d "$service"
}

echo -e "${YELLOW}Starting services with docker-compose...${NC}"
compose build linchange-demo
compose_up postgres linchange-postgres

echo -e "${YELLOW}Waiting for PostgreSQL to be ready...${NC}"
for i in {1..30}; do
    if compose exec -T postgres pg_isready -U linchange >/dev/null 2>&1; then
        echo -e "${GREEN}PostgreSQL is ready.${NC}"
        break
    fi
    sleep 1
done

echo -e "${YELLOW}Starting linchange...${NC}"
compose_up linchange-demo linchange-demo

echo -e "${YELLOW}Waiting for linchange to be healthy on port ${DEMO_HTTP_PORT}...${NC}"
