echo -e "  Health:       ${BLUE}${DEMO_BASE_URL}/healthz${NC}"
echo ""
echo -e "${GREEN}Demo Credentials:${NC}"
echo -e "  Email:    ${DEMO_ADMIN_EMAIL}"
echo -e "  Password: ${DEMO_ADMIN_PASSWORD}"
echo -e "  Domain:   ${DEMO_DOMAIN}"
