#!/usr/bin/env bash
# Linchange Demo Launch Script
# Starts linchange with demo admin credentials for testing
#
# The stack is published on non-standard host ports - each standard port with a
# 5 in front, so 8080 becomes 58080 and IMAP 143 becomes 5143 - so it can run
# beside a mail server on the same machine without binding privileged ports.
# Override any of them by exporting the matching variable, e.g.
#
#   LINCHANGE_HTTP_PORT=9080 ./run-demo.sh

set -euo pipefail

# Colors for output
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
BLUE='\033[0;34m'
NC='\033[0m' # No Color

# Demo credentials
DEMO_ADMIN_EMAIL="admin@localhost"
DEMO_ADMIN_PASSWORD="DemoAdmin123!"
DEMO_DOMAIN="localhost"
DEMO_JWT_SECRET="demo-jwt-secret-change-in-production-$(openssl rand -hex 16)"
DEMO_DB_PASSWORD="linchange"

# Published host ports. Every one of them is the standard port with a 5 in
# front, so the demo never binds a privileged port and never collides with a
# mail server or web server already running on the host. The container keeps
# the standard ports. Override any of them by exporting the matching variable
# before running this script, for example LINCHANGE_HTTP_PORT=9080.
DEMO_SMTP_PORT="${LINCHANGE_SMTP_PORT:-5025}"
DEMO_SMTPS_PORT="${LINCHANGE_SMTPS_PORT:-5465}"
DEMO_SUBMISSION_PORT="${LINCHANGE_SUBMISSION_PORT:-5587}"
DEMO_IMAP_PORT="${LINCHANGE_IMAP_PORT:-5143}"
DEMO_IMAPS_PORT="${LINCHANGE_IMAPS_PORT:-5993}"
DEMO_POP3_PORT="${LINCHANGE_POP3_PORT:-5110}"
DEMO_POP3S_PORT="${LINCHANGE_POP3S_PORT:-5995}"
DEMO_HTTP_PORT="${LINCHANGE_HTTP_PORT:-58080}"
DEMO_HTTPS_PORT="${LINCHANGE_HTTPS_PORT:-58443}"
DEMO_BASE_URL="http://localhost:${DEMO_HTTP_PORT}"

echo -e "${BLUE}╔════════════════════════════════════════════════════════════════╗${NC}"
echo -e "${BLUE}║          Linchange Demo Environment Launcher                   ║${NC}"
echo -e "${BLUE}╚════════════════════════════════════════════════════════════════╝${NC}"
echo ""

# Check if docker and docker-compose are available
if ! command -v docker &> /dev/null; then
    echo -e "${RED}Error: docker not found. Please install Docker.${NC}"
    exit 1
fi

if ! command -v docker compose &> /dev/null && ! command -v docker-compose &> /dev/null; then
    echo -e "${RED}Error: docker compose not found. Please install Docker Compose.${NC}"
    exit 1
fi

# Determine compose command
COMPOSE_CMD="docker compose"
if ! docker compose version &> /dev/null; then
    COMPOSE_CMD="docker-compose"
fi

echo -e "${YELLOW}Demo credentials:${NC}"
echo -e "  Admin email:    ${GREEN}${DEMO_ADMIN_EMAIL}${NC}"
echo -e "  Admin password: ${GREEN}${DEMO_ADMIN_PASSWORD}${NC}"
echo -e "  Domain:         ${GREEN}${DEMO_DOMAIN}${NC}"
echo ""
echo -e "${YELLOW}Host ports:${NC}"
echo -e "  HTTP ${DEMO_HTTP_PORT}  HTTPS ${DEMO_HTTPS_PORT}  (override with LINCHANGE_HTTP_PORT and friends)"
echo ""

# Create config directory if it doesn't exist
mkdir -p config

# Generate the demo config. This is a generated file - the header says so - and
# it is rewritten on every run rather than only when missing, because the
# advertised ports in it have to agree with the ports this run publishes. A
# config left over from an earlier run with different LINCHANGE_*_PORT overrides
# would make Autodiscover send clients to ports nothing is listening on.
CONFIG_FILE="config/linchange.demo.yaml"
if [[ -f "$CONFIG_FILE" ]]; then
