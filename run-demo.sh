for i in {1..60}; do
    if curl -sf "${DEMO_BASE_URL}/healthz" >/dev/null 2>&1; then
        echo -e "${GREEN}Linchange is healthy!${NC}"
        HEALTHY=1
        break
    fi
    sleep 2
done
if [[ "$HEALTHY" -eq 0 ]]; then
    echo -e "${RED}Linchange did not answer on ${DEMO_BASE_URL}/healthz.${NC}"
    echo -e "${YELLOW}Recent logs:${NC}"
    compose logs --tail 40 linchange-demo || true
    exit 1
fi

